(async () => {
  const log = [];
  const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
  const made = await api.notes.add('INST-T1 第一行\n第二行');
  const id = made.note ? made.note.id : made.id;
  setTab('notes');
  setMode('panel', true);
  S.noteOpen = id;
  S.noteEdit = id;
  renderNotes();
  await sleep(500);
  const box = document.querySelector('.note-rich[data-id="' + id + '"]');
  box.focus();
  const r = document.createRange();
  r.selectNodeContents(box);
  r.collapse(true);
  const sel = getSelection();
  sel.removeAllRanges();
  sel.addRange(r);
  document.execCommand('insertText', false, 'HEAD-');
  await sleep(80);
  const rect = box.getBoundingClientRect();
  box.dispatchEvent(new MouseEvent('contextmenu', { bubbles: true, cancelable: true, clientX: rect.left + 20, clientY: rect.top + 10 }));
  await sleep(120);
  document.querySelector('#editMenu [data-act="edit-paste-img"]').click();
  await sleep(1600);
  const cur = (S.data.notes || []).find((n) => n.id === id);
  log.push('text ' + JSON.stringify(cur.text));
  log.push('pics ' + document.querySelectorAll('.note-rich .note-pic').length);
  log.push('count ' + (S.data.notes || []).length);
  await api.notes.remove(id);
  log.push('after ' + (S.data.notes || []).length);
  S.noteEdit = null;
  S.noteOpen = null;
  setMode('idle', true);
  return log;
})()
